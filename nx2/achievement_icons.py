"""Embed the Ocarina of Time achievement badges into the Builder's generated source."""
import concurrent.futures
import json
import math
import os
import sys
import urllib.request

import logo_rgba

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
MANIFEST = os.path.join(ROOT, "assets", "oot-achievement-badges.json")
BADGES = os.path.join(ROOT, "assets", "oot-achievement-badges")
ICON_SIZE = 32


def _custom_fairy():
    """Small, original Hookshot badge for the local-only Navi achievement."""
    out = bytearray(ICON_SIZE * ICON_SIZE * 4)
    for y in range(ICON_SIZE):
        for x in range(ICON_SIZE):
            dx, dy = x + 0.5 - 16, y + 0.5 - 16
            radius = math.hypot(dx, dy)
            colour = None
            if radius <= 14:
                colour = (27, 57, 68, 255)
            if 11.5 <= radius <= 14:
                colour = (224, 190, 88, 255)
            # A bright four-point fairy sparkle with a soft cyan centre.
            if (abs(dx) <= max(1.2, 7.5 - abs(dy)) and abs(dy) <= 7.5) or (
                abs(dy) <= max(1.2, 7.5 - abs(dx)) and abs(dx) <= 7.5
            ):
                colour = (114, 224, 220, 255)
            if radius <= 3.2:
                colour = (245, 255, 235, 255)
            if not colour:
                continue
            at = (y * ICON_SIZE + x) * 4
            out[at:at + 4] = bytes(colour)
    return bytes(out)


def _resize_rgba(width, height, pixels):
    """Premultiplied bilinear resize to ICON_SIZE, returned as straight RGBA."""
    out = bytearray(ICON_SIZE * ICON_SIZE * 4)
    for ty in range(ICON_SIZE):
        sy = max(0.0, (ty + 0.5) * height / ICON_SIZE - 0.5)
        y0, y1 = min(int(sy), height - 1), min(int(sy) + 1, height - 1)
        fy = sy - y0
        for tx in range(ICON_SIZE):
            sx = max(0.0, (tx + 0.5) * width / ICON_SIZE - 0.5)
            x0, x1 = min(int(sx), width - 1), min(int(sx) + 1, width - 1)
            fx = sx - x0
            accum = [0.0, 0.0, 0.0, 0.0]
            for px, py, weight in (
                (x0, y0, (1 - fx) * (1 - fy)),
                (x1, y0, fx * (1 - fy)),
                (x0, y1, (1 - fx) * fy),
                (x1, y1, fx * fy),
            ):
                at = (py * width + px) * 4
                alpha = pixels[at + 3] / 255.0 * weight
                accum[0] += pixels[at] * alpha
                accum[1] += pixels[at + 1] * alpha
                accum[2] += pixels[at + 2] * alpha
                accum[3] += alpha
            at = (ty * ICON_SIZE + tx) * 4
            if accum[3] > 0:
                out[at] = round(accum[0] / accum[3])
                out[at + 1] = round(accum[1] / accum[3])
                out[at + 2] = round(accum[2] / accum[3])
                out[at + 3] = round(accum[3] * 255)
    return bytes(out)


def _pixels_for(icon):
    if not icon["badge"]:
        return _custom_fairy()
    path = os.path.join(BADGES, icon["badge"] + ".png")
    if not os.path.isfile(path):
        raise FileNotFoundError("Missing achievement badge: " + path)
    width, height, pixels = logo_rgba.decode(open(path, "rb").read())
    return _resize_rgba(width, height, pixels)


def header():
    manifest = json.load(open(MANIFEST, encoding="utf-8"))
    icons = manifest["icons"]
    if [icon["id"] for icon in icons] != list(range(len(icons))):
        raise ValueError("achievement icon manifest IDs must be dense and ordered")
    lines = [
        "// generated by nx2/achievement_icons.py: do not edit",
        "#pragma once",
        "static constexpr unsigned hookshot_achievement_icon_size = %d;" % ICON_SIZE,
        "static const unsigned char hookshot_achievement_icons[%d][%d] = {" % (
            len(icons), ICON_SIZE * ICON_SIZE * 4
        ),
    ]
    for icon in icons:
        pixels = _pixels_for(icon)
        lines.append("{")
        for i in range(0, len(pixels), 32):
            lines.append(",".join(str(b) for b in pixels[i:i + 32]) + ",")
        lines.append("},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def write(out_path):
    text = header()
    try:
        with open(out_path, encoding="utf-8") as f:
            if f.read() == text:
                return text
    except OSError:
        pass
    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return text


def download():
    """Optional maintainer command to fetch the manifest's original RA badge PNGs."""
    manifest = json.load(open(MANIFEST, encoding="utf-8"))
    os.makedirs(BADGES, exist_ok=True)
    icons = [icon for icon in manifest["icons"] if icon["badge"]]

    def fetch(icon):
        badge = icon["badge"]
        url = "https://media.retroachievements.org/Badge/" + badge + ".png"
        request = urllib.request.Request(url, headers={"User-Agent": "Hookshot achievement badges"})
        with urllib.request.urlopen(request, timeout=30) as response:
            data = response.read()
        with open(os.path.join(BADGES, badge + ".png"), "wb") as f:
            f.write(data)
        return badge, len(data)

    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
        fetched = list(pool.map(fetch, icons))
    print("Downloaded %d achievement badges (%d bytes)" % (len(fetched), sum(size for _, size in fetched)))


if __name__ == "__main__":
    if len(sys.argv) == 2 and sys.argv[1] == "--download":
        download()
    else:
        out = sys.argv[1] if len(sys.argv) > 1 else "hookshot_achievement_icons.h"
        write(out)
        print("achievement_icons: %s" % out)
